/*
 * Xbox 360 wired controller (045e:028e): only the vendor-class XUSB gamepad
 * interface (0xff/0x5d/0x01), no HID descriptors. Windows binds xusb22.sys
 * to it by vendor/product ID.
 */
#define VDS_X360_USB_VENDOR_ID 0x045e
#define VDS_X360_USB_PRODUCT_ID 0x028e
#define VDS_X360_USB_DEVICE_BCD 0x0114
#define VDS_X360_USB_MANUFACTURER_STRING "Microsoft Corporation"
#define VDS_X360_USB_PRODUCT_STRING "Controller"
#define VDS_X360_USB_GAMEPAD_INTERFACE 0
#define VDS_X360_USB_IN_ENDPOINT 0x81
#define VDS_X360_USB_OUT_ENDPOINT 0x01

static const unsigned char vds_x360_usb_device_descriptor[] = {
	0x12, 0x01, 0x00, 0x02, /* USB 2.0 */
	0xff, 0xff, 0xff, 0x08, /* vendor class, ep0 8 */
	0x5e, 0x04, 0x8e, 0x02, /* 045e:028e */
	0x14, 0x01, /* bcdDevice 1.14 */
	0x01, 0x02, 0x00, 0x01, /* iManufacturer, iProduct, no serial, 1 config */
};


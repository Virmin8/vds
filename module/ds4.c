static const u8 vds_ds4_hid_descriptor[] = {
	0x09, USB_DT_HID, 0x11, 0x01, 0x00, 0x01, USB_DT_REPORT,
	sizeof(vds_ds4_hid_report_descriptor) & 0xff,
	sizeof(vds_ds4_hid_report_descriptor) >> 8,
};

#define VDS_DS4_CONFIG_TOTAL_LENGTH (9 + 9 + 9 + 7 + 7)

static const u8 vds_ds4_configuration_descriptor[] = {
	/* Configuration */
	0x09, 0x02, VDS_DS4_CONFIG_TOTAL_LENGTH, 0x00, 0x01, 0x01, 0x00, 0xc0,
	0xfa,
	/* Interface 0: HID */
	0x09, 0x04, VDS_DS4_HID_INTERFACE, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00,
	/* HID */
	0x09, USB_DT_HID, 0x11, 0x01, 0x00, 0x01, USB_DT_REPORT,
	sizeof(vds_ds4_hid_report_descriptor) & 0xff,
	sizeof(vds_ds4_hid_report_descriptor) >> 8,
	/* Interrupt IN */
	0x07, 0x05, VDS_DS4_HID_IN_ENDPOINT, 0x03, 0x40, 0x00, 0x05,
	/* Interrupt OUT */
	0x07, 0x05, VDS_DS4_HID_OUT_ENDPOINT, 0x03, 0x40, 0x00, 0x05,
};

_Static_assert(sizeof(vds_ds4_hid_report_descriptor) == 507,
	       "unexpected DS4 HID report descriptor size");
_Static_assert(sizeof(vds_ds4_configuration_descriptor) ==
		       VDS_DS4_CONFIG_TOTAL_LENGTH,
	       "unexpected DS4 configuration descriptor size");

